    /**
     * Validación de Cédula Ecuatoriana mediante algoritmo Módulo 10
     */
    public static boolean validarCedula(String cedula) {
        if (cedula == null || cedula.length() != 10) {
            return false;
        }
        if (!cedula.matches("\\d{10}")) {
            return false;
        }
        int provincia = Integer.parseInt(cedula.substring(0, 2));
        if ((provincia < 1 || provincia > 24) && provincia != 30) {
            return false;
        }
        int tercerDigito = Character.getNumericValue(cedula.charAt(2));
        if (tercerDigito >= 6) {
            return false;
        }
        int[] coeficientes = {2, 1, 2, 1, 2, 1, 2, 1, 2};
        int suma = 0;
        for (int i = 0; i < 9; i++) {
            int valor = Character.getNumericValue(cedula.charAt(i)) * coeficientes[i];
            if (valor >= 10) {
                valor -= 9;
            }
            suma += valor;
        }
        int digitoVerificador = (10 - (suma % 10)) % 10;
        int ultimoDigito = Character.getNumericValue(cedula.charAt(9));
        return digitoVerificador == ultimoDigito;
    }
    
    public void insertStudent() {
        try {
            String cedula = jTxtCedula.getText().trim();
            String nombre = jTxtNombre.getText().trim();
            String apellido = jTxtApellido.getText().trim();
            String telefono = jTxtTelefono.getText().trim();
            String direccion = jTxtDireccion.getText().trim();

            if (cedula.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Por favor ingrese la cédula.", "Campo Requerido", JOptionPane.WARNING_MESSAGE);
                jTxtCedula.requestFocus();
                return;
            } else if (cedula.length() != 10) {
                JOptionPane.showMessageDialog(null, "La cédula debe contener exactamente 10 dígitos numéricos.", "Validación Cédula", JOptionPane.WARNING_MESSAGE);
                jTxtCedula.requestFocus();
                return;
            } else if (!validarCedula(cedula)) {
                JOptionPane.showMessageDialog(null, "La cédula ingresada no es válida (cédula ecuatoriana inválida).", "Cédula Inválida", JOptionPane.ERROR_MESSAGE);
                jTxtCedula.requestFocus();
                return;
            }

            if (nombre.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Por favor ingrese el nombre.", "Campo Requerido", JOptionPane.WARNING_MESSAGE);
                jTxtNombre.requestFocus();
                return;
            }

            if (apellido.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Por favor ingrese el apellido.", "Campo Requerido", JOptionPane.WARNING_MESSAGE);
                jTxtApellido.requestFocus();
                return;
            }

            if (telefono.isEmpty()) {
                telefono = "0000000000";
            } else if (telefono.length() != 10) {
                JOptionPane.showMessageDialog(null, "El teléfono debe contener 10 dígitos numéricos.", "Validación Teléfono", JOptionPane.WARNING_MESSAGE);
                jTxtTelefono.requestFocus();
                return;
            }

            if (direccion.isEmpty()) {
                direccion = "SIN DIRECCION";
            }

            Conexion cn = new Conexion();
            Connection conexion = cn.conectar();
            if (conexion == null) {
                JOptionPane.showMessageDialog(null, "No se pudo conectar a la base de datos MySQL.", "Error de Conexión", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Control de duplicados por cédula
            String sqlCheck = "SELECT COUNT(*) FROM ESTUDIANTES WHERE estCedula = ?";
            PreparedStatement psdCheck = conexion.prepareStatement(sqlCheck);
            psdCheck.setString(1, cedula);
            ResultSet rsCheck = psdCheck.executeQuery();
            if (rsCheck.next() && rsCheck.getInt(1) > 0) {
                JOptionPane.showMessageDialog(null, "Ya existe un estudiante registrado con la cédula " + cedula, "Registro Duplicado", JOptionPane.WARNING_MESSAGE);
                jTxtCedula.requestFocus();
                return;
            }

            String sql = "INSERT INTO ESTUDIANTES (estCedula, estNombre, estApellido, estTelefono, estDireccion) VALUES (?,?,?,?,?)";
            PreparedStatement psd = conexion.prepareStatement(sql);
            psd.setString(1, cedula);
            psd.setString(2, nombre);
            psd.setString(3, apellido);
            psd.setString(4, telefono);
            psd.setString(5, direccion);

            int n = psd.executeUpdate();
            if (n > 0) {
                JOptionPane.showMessageDialog(null, "Estudiante registrado con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                showStudents();
                BotonesBloquar();
                TextoBloquear();
                LimpiarTextos();
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(null, "Error al insertar el estudiante: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

