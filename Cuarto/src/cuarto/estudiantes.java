    public void updateStudent() {
        try {
            String cedula = jTxtCedula.getText().trim();
            String nombre = jTxtNombre.getText().trim();
            String apellido = jTxtApellido.getText().trim();
            String telefono = jTxtTelefono.getText().trim();
            String direccion = jTxtDireccion.getText().trim();

            if (cedula.isEmpty()) {
                JOptionPane.showMessageDialog(null, "No se ha seleccionado ningún estudiante.", "Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            if (nombre.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Por favor ingrese el nombre.", "Campo Requerido", JOptionPane.WARNING_MESSAGE);
                jTxtNombre.requestFocus();
                return;
            }

            if (apellido.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Por favor ingrese el apellido.", "Campo Requerido", JOptionPane.WARNING_MESSAGE);
                jTxtApellido.requestFocus();
                return;
            }

            if (telefono.isEmpty()) {
                telefono = "0000000000";
            } else if (telefono.length() != 10) {
                JOptionPane.showMessageDialog(null, "El teléfono debe contener 10 dígitos numéricos.", "Validación Teléfono", JOptionPane.WARNING_MESSAGE);
                jTxtTelefono.requestFocus();
                return;
            }

            if (direccion.isEmpty()) {
                direccion = "SIN DIRECCION";
            }

            Conexion c = new Conexion();
            Connection cc = c.conectar();
            if (cc == null) {
                JOptionPane.showMessageDialog(null, "No se pudo conectar a la base de datos MySQL.", "Error de Conexión", JOptionPane.ERROR_MESSAGE);
                return;
            }
            String sql = "UPDATE ESTUDIANTES SET estNombre=?,estApellido=?,estTelefono=?,estDireccion=? WHERE estCedula=?";
            PreparedStatement psd = cc.prepareStatement(sql);
            psd.setString(1, nombre);
            psd.setString(2, apellido);
            psd.setString(3, telefono);
            psd.setString(4, direccion);
            psd.setString(5, cedula);

            int row = psd.executeUpdate();
            if (row > 0) {
                JOptionPane.showMessageDialog(null, "Estudiante actualizado con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                showStudents();
                BotonesBloquar();
                TextoBloquear();
                LimpiarTextos();
                jBtnEditar.setText("Editar");
            }
        } catch (SQLException ex) {
            Logger.getLogger(estudiantes.class.getName()).log(Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(null, "Error al actualizar: " + ex.getMessage(), "Error SQL", JOptionPane.ERROR_MESSAGE);
        }
    }

